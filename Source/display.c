static inline void bus_delay(void)
{
    /* Complete the GPIO writes, then allow at least 40 ns at 200 MHz.
       The ST7789V requires 15 ns per WR phase and 66 ns per write cycle. */
    __DSB();
    __NOP(); __NOP(); __NOP(); __NOP();
    __NOP(); __NOP(); __NOP(); __NOP();
}

static inline void lcd_byte(uint8_t byte)
{
    GPIOD->odt = (GPIOD->odt & ~LCD_DATA_MASK) | ((uint32_t)byte << 8);
    GPIO_LOW(GPIOD, LCD_WR);
    bus_delay();
    GPIO_HIGH(GPIOD, LCD_WR);
    bus_delay();
}

static void transfer_byte(uint8_t byte, bool data)
{
    if (data)
        GPIO_HIGH(GPIOD, LCD_DC);
    else
        GPIO_LOW(GPIOD, LCD_DC);
    GPIO_LOW(GPIOD, LCD_CS);
    bus_delay();
    lcd_byte(byte);
    GPIO_HIGH(GPIOD, LCD_CS);
    bus_delay();
}

static void command(uint8_t code, const uint8_t *parameters, unsigned count)
{
    transfer_byte(code, false);
    for (unsigned i = 0; i < count; ++i)
        transfer_byte(parameters[i], true);
}

static void data16(uint16_t data)
{
    lcd_byte((uint8_t)(data >> 8));
    lcd_byte((uint8_t)data);
}

static void address_range(uint8_t code, unsigned first, unsigned last)
{
    const uint8_t parameters[] = {
        (uint8_t)(first >> 8), (uint8_t)first, (uint8_t)(last >> 8), (uint8_t)last
    };
    command(code, parameters, sizeof(parameters));
}

static void window(unsigned x, unsigned y, unsigned width, unsigned height)
{
    address_range(0x2a, x, x + width - 1);
    address_range(0x2b, y, y + height - 1);
    command(0x2c, NULL, 0);
    GPIO_HIGH(GPIOD, LCD_DC);
    GPIO_LOW(GPIOD, LCD_CS);
    bus_delay();
}

void display_init(void)
{
    /* Panel timing and voltages from the stock RT-950 Pro V0.27 setup. */
    static const struct {
        uint8_t command;
        uint8_t count;
        uint8_t parameters[14];
    } panel_setup[] = {
        {0xb2, 5, {0x05, 0x05, 0x00, 0x33, 0x33}}, /* Porch timing */
        {0xb7, 1, {0x35}},                         /* Gate voltages */
        {0xc0, 1, {0x2c}},                         /* Panel mode */
        {0xc2, 1, {0x01}},                         /* Enable VRH/VDV settings */
        {0xc3, 1, {0x0f}},                         /* VRH */
        {0xc4, 1, {0x20}},                         /* VDV */
        {0xc6, 1, {0x11}},                         /* Frame rate */
        {0xd0, 2, {0xa4, 0xa1}},                   /* Power control */
        {0xe8, 1, {0x03}},                         /* Equalization timing */
        {0xe9, 3, {0x09, 0x09, 0x08}},             /* Gate timing */
        {0xbb, 1, {0x3f}},                         /* VCOM */
        {0xe0, 14, {0xd0, 0x05, 0x09, 0x09, 0x08, 0x14, 0x28,
                    0x33, 0x3f, 0x07, 0x13, 0x14, 0x28, 0x30}}, /* Positive gamma */
        {0xe1, 14, {0xd0, 0x05, 0x09, 0x09, 0x08, 0x03, 0x24,
                    0x32, 0x32, 0x3b, 0x14, 0x13, 0x28, 0x2f}}, /* Negative gamma */
        {0x36, 1, {0xc0}},                         /* Portrait, both axes reversed */
        {0x3a, 1, {0x05}},                         /* RGB565 on the MCU interface */
        {0x21, 0, {0}},                            /* Inversion on */
        {0x29, 0, {0}},                            /* Display on */
    };

    GPIO_HIGH(GPIOD, LCD_CS | LCD_WR | LCD_RST);
    board_delay_ms(1);
    GPIO_LOW(GPIOD, LCD_RST);
    board_delay_ms(10);
    GPIO_HIGH(GPIOD, LCD_RST);
    board_delay_ms(120);

    command(0x11, NULL, 0); /* Sleep out. */
    board_delay_ms(120);
    for (unsigned i = 0; i < sizeof(panel_setup) / sizeof(panel_setup[0]); ++i)
        command(panel_setup[i].command, panel_setup[i].parameters, panel_setup[i].count);

    board_delay_ms(20);
    display_fill(0, 0, LCD_WIDTH, LCD_HEIGHT, COLOR_BG);
}

void display_fill(unsigned x, unsigned y, unsigned width, unsigned height, uint16_t color)
{
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT || width == 0 || height == 0)
        return;
    if (width > LCD_WIDTH - x)
        width = LCD_WIDTH - x;
    if (height > LCD_HEIGHT - y)
        height = LCD_HEIGHT - y;
    window(x, y, width, height);
    for (unsigned i = width * height; i; --i)
        data16(color);
    GPIO_HIGH(GPIOD, LCD_CS);
}

void display_text(unsigned x, unsigned y, unsigned cells, DisplayFont font,
                  uint16_t color, uint16_t background, const char *text)
{
    if (x >= LCD_WIDTH || y + 8u * font > LCD_HEIGHT)
        return;
    unsigned cell_width = 6u * font;
    if (cells > (LCD_WIDTH - x) / cell_width)
        cells = (LCD_WIDTH - x) / cell_width;
    if (!cells)
        return;
    uint8_t line[40];
    bool end = false;
    for (unsigned i = 0; i < cells; ++i) {
        unsigned c = end ? 0 : (unsigned char)*text++;
        end = c == 0;
        line[i] = c >= 32 && c <= 126 ? (uint8_t)(c - 32) : 0;
    }

    window(x, y, cells * cell_width, font * 8u);
    for (unsigned row = 0; row < 8; ++row) {
        for (unsigned repeat = 0; repeat < (unsigned)font; ++repeat) {
            for (unsigned i = 0; i < cells; ++i) {
                uint8_t pixels = row < 7 ? glyphs[line[i]][row] : 0;
                for (unsigned bit = 0x10u; bit; bit >>= 1) {
                    uint16_t pixel = pixels & bit ? color : background;
                    for (unsigned col = 0; col < (unsigned)font; ++col)
                        data16(pixel);
                }
                for (unsigned col = 0; col < (unsigned)font; ++col)
                    data16(background);
            }
        }
    }
    GPIO_HIGH(GPIOD, LCD_CS);
}
